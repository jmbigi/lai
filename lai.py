    def _ensure_system_prompt(self, messages: List[Dict]) -> List[Dict]:
        """Ensure the messages list starts with a system prompt in the configured language."""
        if messages and messages[0].get("role") == "system":
            return messages
        return [self._system_prompt()] + messages

    def chat_messages(
        self,
        messages: List[Dict],
        tools: Optional[List[Dict]] = None,
        tool_choice: str = "auto",
        stream: bool = False,
        thinking: bool = False,
        temp: float = 0.1,
        max_tokens: int = 2048,
    ) -> Dict:
        """Send a full message list and return content plus native tool calls.

        Used by the agent loop. Non-streaming by design so tool calls are
        returned atomically.
        """
        if not is_local_url(self.base_url):
            return {
                "content": "",
                "tool_calls": [],
                "error": f"Rule 4: local endpoint required, got {self.base_url}",
            }

        payload = {
            "model": self.model,
            "messages": messages,
            "max_tokens": max_tokens,
            "temperature": temp,
            "stream": stream,
            "top_p": 0.95 if thinking else 0.8,
            "top_k": 20,
            "min_p": 0.0,
            "chat_template_kwargs": {"enable_thinking": bool(thinking)},
        }
        if tools:
            payload["tools"] = tools
            payload["tool_choice"] = tool_choice
            payload["parallel_tool_calls"] = False

        if stream:
            return self._chat_messages_stream(payload)

        try:
            with httpx.Client(timeout=300) as client:
                response = client.post(f"{self.base_url}/chat/completions", json=payload)
                response.raise_for_status()
                data = response.json()
            message = (data.get("choices") or [{}])[0].get("message") or {}
            content = message.get("content") or ""
            content = re.sub(
                r"<think(?:ing)?>.*?</think(?:ing)>", "", content, flags=re.DOTALL
            ).strip()
            return {
                "content": content,
                "tool_calls": message.get("tool_calls") or [],
                "finish_reason": (data.get("choices") or [{}])[0].get("finish_reason"),
                "usage": data.get("usage", {}),
            }
        except Exception as exc:
            return {"content": "", "tool_calls": [], "error": str(exc)}

    def _chat_messages_stream(self, payload: Dict) -> Generator[Dict, None, None]:
        """Stream chat messages with native tool calls support.

        Yields dict chunks with keys: content, tool_calls, finish_reason, usage
        """
        try:
            with (
                httpx.Client(timeout=300) as client,
                client.stream(
                    "POST", f"{self.base_url}/chat/completions", json=payload
                ) as response,
            ):
                response.raise_for_status()
                for line in response.iter_lines():
                    if not line:
                        continue
                    if line.startswith("data: "):
                        data_str = line[6:]
                        if data_str == "[DONE]":
                            yield {"finish_reason": "stop", "content": "", "tool_calls": []}
                            break
                        try:
                            chunk = json.loads(data_str)
                        except json.JSONDecodeError:
                            continue
                        choices = chunk.get("choices") or []
                        if not choices:
                            continue
                        delta = choices[0].get("delta", {})
                        content = delta.get("content")
                        tool_calls = delta.get("tool_calls")
                        finish_reason = choices[0].get("finish_reason")
                        yield {
                            "content": content or "",
                            "tool_calls": tool_calls or [],
                            "finish_reason": finish_reason,
                        }
        except Exception as exc:
            yield {"content": "", "tool_calls": [], "error": str(exc)}

