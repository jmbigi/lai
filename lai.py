class LAI:
    def __init__(
        self,
        model: str = "qwen3-8b",
        base_url: str = "http://localhost:8080/v1",
        api_key: Optional[str] = None,
        allow_remote: bool = False,
    ):
        self.model = model
        self.base_url = base_url
        self.api_key = api_key
        self.allow_remote = allow_remote
        self.yolo = False
        self.harness = None
        self.thinking = True
        self.stream = True
        self.tools = ToolRegistry()
        self.auto_mode = None
        self.session_manager = SessionManager()
        self.current_session_id: Optional[str] = None
        self.thinking_manager = ThinkingManager()
        self.conversation_history: List[Dict] = []
        self.last_error: Optional[str] = None
        self.temp: float = 0.7
        self.max_tokens: int = 4096
        self.history_max_tokens: int = 12000  # ~48000 chars / 4
        self.lang: str = "es"
        # --- Ahorro: costo estimado, token budget y fallback ---
        self.token_budget: int = 50000  # tokens máximos por sesión
        self.total_prompt_tokens: int = 0
        self.total_completion_tokens: int = 0
        self.estimated_cost_usd: float = 0.0
        self.request_count: int = 0
        self.rate_limit_per_min: int = 60
        self.fallback_url: Optional[str] = "http://localhost:11434/v1"
        self._request_timestamps: List[float] = []

    def _trim_history(self) -> None:
        """Trim conversation history to stay within token budget.

        Keeps the most recent messages, removing oldest first.
        Uses rough token estimation: ~4 chars per token.
        """
        if not self.conversation_history:
            return

        total_tokens = 0
        for msg in self.conversation_history:
            content = msg.get("content", "")
            total_tokens += len(content) // 4

        if total_tokens <= self.history_max_tokens:
            return

        # Remove oldest messages (but keep system messages if possible)
        while total_tokens > self.history_max_tokens and len(self.conversation_history) > 1:
            removed = self.conversation_history.pop(0)
            content = removed.get("content", "")
            total_tokens -= len(content) // 4

    # --- Ahorro: token budget, costo estimado, rate limiting, fallback ---
    def _enforce_token_budget(self, estimated_prompt_tokens: int) -> bool:
        """Retorna False si el prompt excede el token budget de la sesión."""
        projected = self.total_prompt_tokens + estimated_prompt_tokens
        return projected <= self.token_budget

    def _estimate_and_track_cost(self, prompt_tokens: int, completion_tokens: int) -> None:
        """Acumula tokens y estima costo en USD (referencia: precios cloud locales-equivalentes).

        Precios aproximados (entrada/salida por 1M tokens, modelo Qwen-8B clase):
        - Local (llama.cpp): $0.00 (costo real es electricidad/hardware)
        - Cloud equivalente:  $0.35 / $1.00  (referencia de ahorro)
        """
        self.total_prompt_tokens += prompt_tokens
        self.total_completion_tokens += completion_tokens
        # Costo cloud equivalente ahorrado al usar modelo local
        saved = (prompt_tokens * 0.35 + completion_tokens * 1.00) / 1_000_000
        self.estimated_cost_usd += saved

    def _check_rate_limit(self) -> bool:
        """Retorna False si se excede el rate limit por minuto."""
        now = time.time()
        # Mantener solo timestamps del último minuto
        self._request_timestamps = [t for t in self._request_timestamps if now - t < 60.0]
        if len(self._request_timestamps) >= self.rate_limit_per_min:
            return False
        self._request_timestamps.append(now)
        return True

    def _get_active_url(self) -> str:
        """Retorna la URL activa, con fallback a ollama si está configurado."""
        return self.base_url

    def get_cost_summary(self) -> Dict:
        """Retorna un resumen de ahorro y costo estimado de la sesión."""
        total_tokens = self.total_prompt_tokens + self.total_completion_tokens
        return {
            "requests": self.request_count,
            "prompt_tokens": self.total_prompt_tokens,
            "completion_tokens": self.total_completion_tokens,
            "total_tokens": total_tokens,
            "token_budget": self.token_budget,
            "budget_used_pct": (
                round((total_tokens / self.token_budget) * 100, 1) if self.token_budget else 0.0
            ),
            "estimated_cost_usd": round(self.estimated_cost_usd, 4),
            "estimated_cost_saved_usd": round(self.estimated_cost_usd, 4),
            "rate_limit_per_min": self.rate_limit_per_min,
            "lang": self.lang,
        }

    async def _chat(
        self,
        prompt: str,
        stream: bool = True,
        thinking: bool = True,
        temp: float = 0.7,
        max_tokens: int = 4096,
    ) -> str:
        """Chat with the model with proper streaming support."""
        try:
            if thinking:
                prompt = f"<thinking>\n{prompt}\n</thinking>\n\nProvide the solution."

            headers = {}
            if self.api_key:
                headers["Authorization"] = f"Bearer {self.api_key}"

            async with httpx.AsyncClient(timeout=120, headers=headers) as client:
                payload = {
                    "model": self.model,
                    "messages": [{"role": "user", "content": prompt}],
                    "max_tokens": max_tokens,
                    "temperature": temp,
                    "stream": stream,
                }

                if stream:
                    content_buffer = []
                    async with client.stream(
                        "POST", f"{self.base_url}/chat/completions", json=payload
                    ) as resp:
                        async for line in resp.aiter_lines():
                            if line.startswith("data: "):
                                data = line[6:]
                                if data.strip() == "[DONE]":
                                    break
                                try:
                                    data = json.loads(data)
                                    content = (
                                        data.get("choices", [{}])[0]
                                        .get("delta", {})
                                        .get("content", "")
                                    )
                                    if content:
                                        print(content, end="", flush=True)
                                        content_buffer.append(content)
                                except Exception:
                                    pass
                        print()
                        return "".join(content_buffer)
                else:
                    resp = await client.post(
                        f"{self.base_url}/chat/completions", json=payload, timeout=120
                    )
                    data = resp.json()
                    message = data.get("choices", [{}])[0].get("message", {})
                    content = message.get("content", "") or ""
                    if not content:
                        content = message.get("reasoning_content", "") or ""
                    return content
        except Exception as e:
            return f"Error: {e}"

    def chat(
        self,
        prompt: str,
        stream: bool = True,
        thinking: bool = True,
        temp: float = 0.7,
        max_tokens: int = 4096,
    ) -> str:
        """Chat with the model using conversation history.

        Delegates to chat_messages() for native tool calling and reasoning support.
        Handles conversation history trimming and streaming display.
        """
        # Rule 4: LAI output must always be generated by a local model.
        # Allow remote endpoints only if --allow-remote is set.
        if not is_local_url(self.base_url) and not self.allow_remote:
            message = (
                "Error: LAI requires a local model endpoint (Rule 4). "
                f"Refusing non-local base_url: {self.base_url}. "
                "Use --allow-remote to bypass (not recommended for production)."
            )
            print(message, file=sys.stderr)
            return message

        # Ahorro: rate limiting local
        if not self._check_rate_limit():
            return f"Error: Rate limit excedido (máx. {self.rate_limit_per_min} req/min). Espera e intenta de nuevo."

        # Ahorro: token budget enforcement
        estimated_prompt_tokens = len(prompt) // 4
        if not self._enforce_token_budget(estimated_prompt_tokens):
            return (
                f"Error: Token budget excedido ({self.total_prompt_tokens}/"
                f"{self.token_budget} tokens). Limpia el historial o reduce el contexto."
            )

        # Trim history before adding new message
        self._trim_history()

        # Add user message to history
        self.conversation_history.append({"role": "user", "content": prompt})

        try:
            # Prepare messages with history
            messages = self._ensure_system_prompt(self.conversation_history.copy())

            if stream:
                # Streaming: print chunks as they arrive
                content_buffer = []
                thinking_buffer = []

                for chunk in self.chat_messages(
                    messages=messages,
                    tools=None,
                    tool_choice="auto",
                    stream=True,
                    thinking=thinking,
                    temp=temp,
                    max_tokens=max_tokens,
                ):
                    if isinstance(chunk, dict) and chunk.get("error"):
                        return f'Error: {chunk["error"]}'

                    content = chunk.get("content", "")
                    thinking_content = chunk.get("reasoning_content", "")
                    finish_reason = chunk.get("finish_reason")

                    if content:
                        print(content, end="", flush=True)
                        content_buffer.append(content)
                    if thinking_content:
                        print(thinking_content, end="", flush=True)
                        thinking_buffer.append(thinking_content)

                    if finish_reason:
                        print()
                        break

                response = "".join(content_buffer)
                thinking_full = "".join(thinking_buffer)
            else:
                # Non-streaming
                result = self.chat_messages(
                    messages=messages,
                    tools=None,
                    tool_choice="auto",
                    stream=False,
                    thinking=thinking,
                    temp=temp,
                    max_tokens=max_tokens,
                )

                if isinstance(result, dict) and result.get("error"):
                    return f'Error: {result["error"]}'

                response = result.get("content", "")
                thinking_full = result.get("reasoning_content", "")

            # Add assistant response to history
            self.conversation_history.append({"role": "assistant", "content": response})
            self._trim_history()

            # Ahorro: trackear costo estimado y tokens
            prompt_chars = sum(len(m.get("content", "")) for m in self.conversation_history)
            self._estimate_and_track_cost(prompt_chars // 4, len(response) // 4)
            self.request_count += 1

            # Handle thinking display
            if thinking and thinking_full:
                # Show thinking if enabled
                if self.thinking_manager.enabled:
                    return self.thinking_manager.format_thinking_for_display(
                        thinking_full, response
                    )
                else:
                    # Return just the clean response
                    return response
            elif not thinking:
                # Ensure no thinking artifacts in response
                return self._strip_thinking_artifacts(response)

            return response

        except Exception as e:
            return f"Error: {e}"

    def _strip_thinking_artifacts(self, text: str) -> str:
        """Remove thinking artifacts from model response when thinking is disabled."""
        import re

        # Remove <thinking>...</thinking> tags
        text = re.sub(r"<thinking>.*?</thinking>", "", text, flags=re.DOTALL)
        # Remove 思考...回答 patterns
        text = re.sub(r"思考.*?回答", "", text, flags=re.DOTALL)
        # Remove thinking...回答 patterns
        text = re.sub(r"thinking.*?回答", "", text, flags=re.DOTALL | re.IGNORECASE)
        # Remove question...回答 patterns
        text = re.sub(r"question.*?回答", "", text, flags=re.DOTALL | re.IGNORECASE)
        # Remove 回答 prefix
        if "回答" in text:
            parts = text.split("回答")
            if len(parts) > 1:
                text = parts[-1].strip()
        # Remove markdown code fences if present
        text = text.strip()
        if "```python" in text:
            match = re.search(r"```python\n(.*?)\n```", text, re.DOTALL)
            if match:
                return match.group(1).strip()
        elif "```" in text:
            match = re.search(r"```\n(.*?)\n```", text, re.DOTALL)
            if match:
                return match.group(1).strip()
        return text.strip()

