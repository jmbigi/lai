def review_cmd(lai: LAI, args):
    """Review a file or directory with the local model.

    Files are chunked with line numbers so the model can cite exact locations.
    """
    path = args.path
    if not os.path.exists(path):
        print(f'Error: path not found: {path}')
        return

    if os.path.isfile(path):
        files = [path]
    else:
        files = []
        skip = {'__pycache__', 'node_modules', '.git', 'venv', 'env', '.venv', '.ruff_cache'}
        for root, dirs, names in os.walk(path):
            dirs[:] = [d for d in dirs if d not in skip and not d.startswith('.')]
            for name in names:
                if name.endswith(
                    (
                        '.py',
                        '.js',
                        '.ts',
                        '.go',
                        '.rs',
                        '.sh',
                        '.md',
                        '.yaml',
                        '.yml',
                        '.json',
                        '.toml',
                    )
                ):
                    files.append(os.path.join(root, name))

    if not files:
        print('No reviewable files found.')
        return

    print(f'Reviewing {len(files)} file(s), focus: {args.focus}')
    all_results = []
    for filepath in files:
        try:
            with open(filepath, 'r', encoding='utf-8', errors='ignore') as handle:
                lines = handle.read().splitlines()
        except OSError as exc:
            print(f'Skipping {filepath}: {exc}')
            continue
        if not lines:
            continue

        chunk_size = 120
        file_findings = []
        for start in range(0, len(lines), chunk_size):
            chunk = lines[start : start + chunk_size]
            numbered = '\n'.join(f'{start + i + 1:4d}: {line}' for i, line in enumerate(chunk))
            prompt = f"""You are a senior code reviewer.
File: {filepath}
Focus: {args.focus}

Return concise, actionable findings. For each finding include:
- severity (P0/P1/P2)
- line number
- problem
- suggested fix
Do not rewrite the whole file. If there are no issues, reply exactly: No issues found.

Code:
{numbered}
"""
            result = lai.chat(prompt, stream=False, thinking=False, temp=0.1, max_tokens=1200)
            if result and not result.startswith('Error:'):
                file_findings.append(result.strip())

        if file_findings:
            all_results.append({'file': filepath, 'findings': file_findings})

    if args.format == 'json':
        print(json.dumps(all_results, indent=2, ensure_ascii=False))
        return

    if args.format == 'sarif':
        sarif = {
            'version': '2.1.0',
            '$schema': 'https://json.schemastore.org/sarif-2.1.0.json',
            'runs': [
                {
                    'tool': {
                        'driver': {
                            'name': 'lai-review',
                            'version': get_version(),
                            'informationUri': 'https://github.com/kubuntu/lai',
                            'rules': [],
                        }
                    },
                    'results': [],
                }
            ],
        }
        rule_id = 0
        for entry in all_results:
            for finding_text in entry['findings']:
                # Parse findings for SARIF (simplified)
                lines = finding_text.strip().split('\n')
                for line in lines:
                    if 'P0' in line or 'P1' in line or 'P2' in line:
                        rule_id += 1
                        sarif['runs'][0]['results'].append(
                            {
                                'ruleId': f'LAI-{rule_id:04d}',
                                'level': 'error'
                                if 'P0' in line
                                else 'warning'
                                if 'P1' in line
                                else 'note',
                                'message': {'text': line.strip()},
                                'locations': [
                                    {
                                        'physicalLocation': {
                                            'artifactLocation': {'uri': entry['file']},
                                            'region': {'startLine': 1},
                                        }
                                    }
                                ],
                            }
                        )
        print(json.dumps(sarif, indent=2, ensure_ascii=False))
        return

    for entry in all_results:
        print(f'\n=== {entry["file"]} ===')
        for finding in entry['findings']:
            print(finding)

    if not all_results:
        print('No issues found.')


