    def serve(self, host: str = "127.0.0.1", port: int = 8082):
        """Minimal OpenAI-compatible API for the local model.

        Endpoints: /health, /v1/models, /v1/chat/completions.
        Binds to loopback by default; use --host only on trusted networks.
        """
        lai = self

        class Handler(http.server.BaseHTTPRequestHandler):
            def log_message(self, _fmt, *args):
                return

            def _json(self, status: int, payload: Dict):
                body = json.dumps(payload, ensure_ascii=False).encode("utf-8")
                self.send_response(status)
                self.send_header("Content-Type", "application/json; charset=utf-8")
                self.send_header("Content-Length", str(len(body)))
                self.end_headers()
                self.wfile.write(body)

            def do_GET(self):
                if self.path in ("/health", "/v1/health"):
                    self._json(200, {"status": "ok", "model": lai.model})
                elif self.path == "/v1/models":
                    self._json(
                        200,
                        {
                            "object": "list",
                            "data": [
                                {
                                    "id": lai.model,
                                    "object": "model",
                                    "owned_by": "local",
                                }
                            ],
                        },
                    )
                else:
                    self._json(404, {"error": "not found"})

            def do_POST(self):
                if self.path != "/v1/chat/completions":
                    self._json(404, {"error": "not found"})
                    return
                try:
                    length = int(self.headers.get("Content-Length", "0"))
                except ValueError:
                    length = 0
                if length <= 0 or length > 2_000_000:
                    self._json(413, {"error": "invalid or oversized request body"})
                    return
                try:
                    body = json.loads(self.rfile.read(length))
                except (json.JSONDecodeError, UnicodeDecodeError):
                    self._json(400, {"error": "invalid JSON"})
                    return

                messages = body.get("messages") or []
                if not isinstance(messages, list) or not messages:
                    self._json(400, {"error": "messages is required"})
                    return

                tools = body.get("tools")
                tool_choice = body.get("tool_choice", "auto")
                stream = body.get("stream", False)
                temperature = float(body.get("temperature", 0.7))
                max_tokens = int(body.get("max_tokens", 2048))
                model = body.get("model", lai.model)

                completion_id = f"chatcmpl-{uuid.uuid4().hex}"
                created = int(time.time())

                if stream:
                    # Streaming response with tool calls support
                    self.send_response(200)
                    self.send_header("Content-Type", "text/event-stream")
                    self.send_header("Cache-Control", "no-cache")
                    self.send_header("Connection", "keep-alive")
                    self.end_headers()

                    try:
                        for chunk_data in lai.chat_messages(
                            messages=messages,
                            tools=tools,
                            tool_choice=tool_choice,
                            stream=True,
                            thinking=False,
                            temp=temperature,
                            max_tokens=max_tokens,
                        ):
                            if isinstance(chunk_data, dict) and chunk_data.get("error"):
                                error_chunk = {
                                    "id": completion_id,
                                    "object": "chat.completion.chunk",
                                    "created": created,
                                    "model": model,
                                    "choices": [
                                        {
                                            "index": 0,
                                            "delta": {},
                                            "finish_reason": "error",
                                        }
                                    ],
                                }
                                self.wfile.write(
                                    f"data: {json.dumps(error_chunk)}\n\n".encode("utf-8")
                                )
                                break

                            content = chunk_data.get("content", "")
                            tool_calls = chunk_data.get("tool_calls", [])
                            finish_reason = chunk_data.get("finish_reason")

                            delta = {}
                            if content:
                                delta["content"] = content
                            if tool_calls:
                                delta["tool_calls"] = tool_calls

                            chunk = {
                                "id": completion_id,
                                "object": "chat.completion.chunk",
                                "created": created,
                                "model": model,
                                "choices": [
                                    {
                                        "index": 0,
                                        "delta": delta,
                                        "finish_reason": finish_reason,
                                    }
                                ],
                            }
                            self.wfile.write(f"data: {json.dumps(chunk)}\n\n".encode("utf-8"))
                            self.wfile.flush()

                            if finish_reason:
                                break
                    except Exception:
                        error_chunk = {
                            "id": completion_id,
                            "object": "chat.completion.chunk",
                            "created": created,
                            "model": model,
                            "choices": [
                                {
                                    "index": 0,
                                    "delta": {},
                                    "finish_reason": "error",
                                }
                            ],
                        }
                        self.wfile.write(f"data: {json.dumps(error_chunk)}\n\n".encode("utf-8"))
                    finally:
                        self.wfile.write(b"data: [DONE]\n\n")
                    return

                # Non-streaming response with tool calls support
                try:
                    result = lai.chat_messages(
                        messages=messages,
                        tools=tools,
                        tool_choice=tool_choice,
                        stream=False,
                        thinking=False,
                        temp=temperature,
                        max_tokens=max_tokens,
                    )
                except Exception as exc:
                    self._json(502, {"error": str(exc)})
                    return

                if isinstance(result, dict) and result.get("error"):
                    self._json(502, {"error": result["error"]})
                    return

                content = result.get("content", "")
                tool_calls = result.get("tool_calls", [])
                finish_reason = result.get("finish_reason", "stop")
                usage = result.get("usage", {})

                message = {"role": "assistant", "content": content}
                if tool_calls:
                    message["tool_calls"] = tool_calls

                self._json(
                    200,
                    {
                        "id": completion_id,
                        "object": "chat.completion",
                        "created": created,
                        "model": model,
                        "choices": [
                            {
                                "index": 0,
                                "message": message,
                                "finish_reason": finish_reason,
                            }
                        ],
                        "usage": usage
                        or {
                            "prompt_tokens": 0,
                            "completion_tokens": 0,
                            "total_tokens": 0,
                        },
                    },
                )

        server = http.server.ThreadingHTTPServer((host, port), Handler)
        print(f"LAI API listening on http://{host}:{port}")
        print("Endpoints: /health, /v1/models, /v1/chat/completions")
        try:
            server.serve_forever()
        except KeyboardInterrupt:
            print("\nStopping server.")
        finally:
            server.server_close()

