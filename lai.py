# Global LAI instance for session persistence
_lai_instance: Optional[LAI] = None


def get_lai_instance(
    model: str = 'qwen3-8b', base_url: str = 'http://localhost:8080/v1', lang: str = 'es'
) -> LAI:
    """Get or create the singleton LAI instance.

    Recreate it when the requested model or endpoint changes; previously the
    first instance silently ignored later --model/--base-url flags.
    """
    global _lai_instance
    if _lai_instance is None or _lai_instance.model != model or _lai_instance.base_url != base_url:
        _lai_instance = LAI(model=model, base_url=base_url)
    _lai_instance.lang = lang
    return _lai_instance


def chat_cmd(args):
    lai = get_lai_instance(
        model=args.model, base_url=args.base_url, lang=getattr(args, 'lang', 'es')
    )
    stream = args.stream if args.stream else (not args.no_stream)
    thinking = args.thinking if args.thinking else (not args.no_thinking)
    temp = args.temp or 0.7
    max_tokens = args.max_tokens or 4096

    if args.interactive:
        print("Interactive mode - type 'exit' or 'quit' to quit")
        print("Type 'clear' to clear conversation history")
        while True:
            try:
                prompt = input('You: ')
                if prompt.lower() in ('exit', 'quit'):
                    break
                if prompt.lower() == 'clear':
                    lai.conversation_history.clear()
                    print('Conversation history cleared.')
                    continue
                response = lai.chat(
                    prompt, stream=stream, thinking=thinking, temp=temp, max_tokens=max_tokens
                )
                print()
            except (EOFError, KeyboardInterrupt):
                print()
                break
    else:
        prompt = ' '.join(args.prompt) if args.prompt else ''
        if not prompt:
            print('Error: No prompt provided')
            return
        response = lai.chat(
            prompt, stream=stream, thinking=thinking, temp=temp, max_tokens=max_tokens
        )
        print(response)


