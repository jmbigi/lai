def find_cmd(lai: LAI, args):
    root_depth = os.path.abspath(args.path).rstrip(os.sep).count(os.sep)
    found = 0
    for root, dirs, files in os.walk(args.path):
        depth = os.path.abspath(root).rstrip(os.sep).count(os.sep) - root_depth
        if args.max_depth is not None and depth >= args.max_depth:
            dirs[:] = []
        for name in dirs + files:
            if not fnmatch.fnmatch(name, args.pattern):
                continue
            full = os.path.join(root, name)
            if args.type == 'f' and not os.path.isfile(full):
                continue
            if args.type == 'd' and not os.path.isdir(full):
                continue
            if args.type == 'l' and not os.path.islink(full):
                continue
            print(full)
            found += 1
    if not found:
        print(f'No files matching {args.pattern}')


